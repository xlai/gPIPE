# Golden tests (#17): Cheung et al. (2022) Table 1, the 12-subject trace of the
# sedentary-break example (fixtures/cheung2022_table1.csv).
#
# Given the printed p_jk, the PIPE estimate is deterministic: w = n + 1,
# untried p = 0.5, MED target on a 5 x 5 grid. 2-EQ tapers to eps = 0.0425 over
# N = 125 subjects; 1-EQ uses eps = 0.05. The paper prints p = 0.95 at 1-EQ
# step 2, exactly 1 - eps; the rounded value is replaced by 0.9505.

cheung_levels <- c(5, 5)

cheung_eps <- function(algorithm, n) {
  if (algorithm == "2-EQ") ref_taper(n, N = 125, eps = 0.0425) else 0.05
}

# Replays one algorithm and calls `check(step, row, gamma_before, gamma_after)`.
replay_cheung <- function(impl, algorithm, check) {
  tab <- read_cheung_table1()
  tab <- tab[tab$algorithm == algorithm, ]
  K <- prod(cheung_levels)
  p <- rep(0.5, K)
  n <- rep(0, K)
  gamma <- impl$estimate(cheung_levels, p, n, cheung_eps(algorithm, 0), "n+1", "MED")
  for (i in seq_len(nrow(tab))) {
    k <- tab$level_A[i] + cheung_levels[1] * (tab$level_B[i] - 1)
    p[k] <- tab$p_used[i]
    n[k] <- n[k] + 1
    before <- gamma
    gamma <- impl$estimate(cheung_levels, p, n, cheung_eps(algorithm, i), "n+1", "MED")
    check(i, tab[i, ], k, before, gamma)
  }
}

for (algorithm in c("2-EQ", "1-EQ")) {
  desc <- sprintf("Cheung Table 1 MED estimates (%s)", algorithm)
  test_each_impl(desc, "estimate", function(impl) {
    replay_cheung(impl, algorithm, function(i, row, k, before, gamma) {
      med <- ref_minimal(cheung_levels, gamma == 1)
      expect_equal(sort(med), parse_dose_labels(row$med_hat, cheung_levels[1]),
                   info = sprintf("%s step %d", algorithm, i))
    })
  })

  desc <- sprintf("Cheung Table 1 doses lie in S1 u S0 (%s)", algorithm)
  test_each_impl(desc, "cheung_candidates", function(impl) {
    if (is.null(impl$estimate)) skip("no `estimate` in the adapter yet (#18)")
    replay_cheung(impl, algorithm, function(i, row, k, before, gamma) {
      expect_true(k %in% impl$cheung_candidates(cheung_levels, before),
                  info = sprintf("%s step %d", algorithm, i))
    })
  })
}

test_each_impl("S1 u S0 on the extreme configurations", "cheung_candidates", function(impl) {
  for (levels in list(c(5, 5), c(3, 4), c(2, 3, 2))) {
    K <- prod(levels)
    expect_equal(impl$cheung_candidates(levels, rep(0L, K)), K)
    expect_equal(impl$cheung_candidates(levels, rep(1L, K)), 1)
  }
  # 5 x 5, U generated by (4, 5) and (5, 3): S1 = U except (5, 5), whose lower
  # covers are both in U; S0 = (3, 5), (4, 3), (4, 4), (5, 2).
  gamma <- matrix(0L, 5, 5)
  gamma[4, 5] <- gamma[5, 3:5] <- 1L
  expected <- c(matrix(1:25, 5, 5)[cbind(c(4, 5, 5, 3, 4, 4, 5), c(5, 3, 4, 5, 3, 4, 2))])
  expect_equal(sort(impl$cheung_candidates(c(5, 5), c(gamma))), sort(expected))
})
